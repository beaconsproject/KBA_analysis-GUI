# Build docs/userguide.md from the per-step guidance files shown in the app's Guidance tab.
#
# Run from the app folder (the one containing ui.R):
#   Rscript docs/build_userguide.R
# or in R:  source("docs/build_userguide.R")
#
# Edit the *_doc.md files, not userguide.md: it is overwritten every time this script runs.

docs_dir <- "docs"
if (!dir.exists(docs_dir) || !file.exists("ui.R")) {
  stop("Run this script from the KBA_analysis-GUI folder (the one containing ui.R).")
}

# Same order as the Guidance tab in ui.R
sections <- c(
  "setParams_doc.md",
  "addLayers_doc.md",
  "builderInput_doc.md",
  "runBuilder_doc.md",
  "KBAreduced_doc.md",
  "assessRep_doc.md",
  "createNet_doc.md",
  "reviewAnalysis_doc.md",
  "dwd_doc.md"
)
out_file <- file.path(docs_dir, "userguide.md")

missing <- sections[!file.exists(file.path(docs_dir, sections))]
if (length(missing) > 0) stop("Missing file(s) in docs/: ", paste(missing, collapse = ", "))

# Renumber headings so the highest heading in a file becomes `target` (##) and each deeper level
# used in the file is one step lower (skipped levels are closed: # then ### becomes ## then ###).
# Lines inside ``` code blocks are left alone.
shift_headings <- function(lines, target = 2) {
  in_code <- cumsum(grepl("^\\s*```", lines)) %% 2 == 1
  is_head <- grepl("^#{1,6}\\s", lines) & !in_code
  if (!any(is_head)) return(lines)
  levels <- nchar(sub("^(#+).*", "\\1", lines[is_head]))
  new_levels <- pmin(match(levels, sort(unique(levels))) + target - 1, 6)
  lines[is_head] <- paste0(strrep("#", new_levels), sub("^#+", "", lines[is_head]))
  lines
}

# Image paths are kept as they are. Put documentation images in docs/pics and reference them as
# src="pics/<file>.png": global.R serves docs/pics at "pics/" in the app, and on GitHub the path
# resolves from docs/.

# GitHub-style anchor for the table of contents
anchor <- function(title) {
  a <- tolower(trimws(title))
  a <- gsub("[^a-z0-9 _-]", "", a)
  gsub(" ", "-", a)
}

body <- character(0)
toc  <- character(0)
for (f in sections) {
  lines <- readLines(file.path(docs_dir, f), warn = FALSE, encoding = "UTF-8")
  lines <- shift_headings(lines)

  # trim blank lines at the start and end of each section
  keep <- which(nzchar(trimws(lines)))
  if (length(keep) == 0) next
  lines <- lines[min(keep):max(keep)]

  top <- grep("^##\\s", lines, value = TRUE)[1]
  if (!is.na(top)) {
    title <- sub("^##\\s+", "", top)
    toc <- c(toc, sprintf("- [%s](#%s)", title, anchor(title)))
  }
  body <- c(body, lines, "", "---", "")
}

header <- c(
  "# KBA Analysis App: User Guide",
  "",
  sprintf("<!-- Generated by docs/build_userguide.R on %s. Do not edit: edit the *_doc.md files and rerun the script. -->",
          format(Sys.Date())),
  "",
  "## Contents",
  "",
  toc,
  "",
  "---",
  ""
)

guide_md <- c(header, head(body, -3))
writeLines(enc2utf8(guide_md), out_file, useBytes = TRUE)
message("Wrote ", out_file, " (", length(sections), " sections).")

#########################################################
# PDF version: docs/userguide.pdf (downloaded from the User guide tab)
#########################################################
# Markdown -> HTML (markdown package, no pandoc needed) -> PDF with Chrome or Edge in headless mode.
# Only the person building the docs needs Chrome/Edge; app users just download the PDF.
# Set the CHROME_PATH environment variable if the browser is not found.

find_browser <- function() {
  candidates <- c(
    Sys.getenv("CHROME_PATH"),
    file.path(Sys.getenv(c("PROGRAMFILES", "PROGRAMFILES(X86)", "LOCALAPPDATA")), "Google/Chrome/Application/chrome.exe"),
    file.path(Sys.getenv(c("PROGRAMFILES", "PROGRAMFILES(X86)")), "Microsoft/Edge/Application/msedge.exe"),
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    Sys.which(c("google-chrome", "chromium", "chromium-browser", "microsoft-edge"))
  )
  candidates <- candidates[nzchar(candidates) & file.exists(candidates)]
  if (length(candidates) == 0) NA_character_ else normalizePath(candidates[1])
}

pdf_file <- file.path(docs_dir, "userguide.pdf")
browser_exe <- find_browser()

if (is.na(browser_exe)) {
  warning("Chrome or Edge not found: ", pdf_file, " was not updated. Set CHROME_PATH and rerun.")
} else {
  html_body <- markdown::markdownToHTML(text = paste(guide_md, collapse = "\n"), fragment.only = TRUE)

  # markdown doesn't add ids to headings: add them so the table of contents links work in the PDF
  for (h in regmatches(html_body, gregexpr("<h2>[^<]+</h2>", html_body))[[1]]) {
    title <- sub("^<h2>(.*)</h2>$", "\\1", h)
    html_body <- sub(h, sprintf('<h2 id="%s">%s</h2>', anchor(title), title), html_body, fixed = TRUE)
  }

  css <- "
    @page { size: Letter; margin: 2cm 2cm 2.2cm 2cm; }
    body  { font-family: 'Segoe UI', 'Helvetica Neue', Helvetica, Arial, sans-serif;
            font-size: 10.5pt; line-height: 1.5; color: #222; }
    h1    { font-size: 24pt; font-weight: 600; color: #2c5f2d; margin: 0 0 0.4em 0; }
    h2    { font-size: 16pt; font-weight: 600; color: #2c5f2d; border-bottom: 1px solid #c8d5c8;
            padding-bottom: 4px; margin-top: 0; page-break-before: always; }
    h2#contents { page-break-before: avoid; }
    h3    { font-size: 12.5pt; font-weight: 600; color: #333; margin-top: 1.3em; }
    h4    { font-size: 11pt; font-weight: 600; color: #444; }
    h2, h3, h4 { page-break-after: avoid; }
    p, li { orphans: 3; widows: 3; }
    strong { font-weight: 600; }
    img   { max-width: 100%; page-break-inside: avoid; }
    table { border-collapse: collapse; margin: 8px 0; font-size: 9.5pt; page-break-inside: avoid; }
    th, td { border: 1px solid #ccc; padding: 4px 8px; vertical-align: top; }
    th    { background: #eef3ee; }
    code  { font-family: Consolas, 'Courier New', monospace; font-size: 9.5pt; background: #f4f4f4; padding: 0 3px; }
    a     { color: #2c5f2d; text-decoration: none; }
    hr    { display: none; }
  "
  # Written in docs/ so relative image paths (pics/...) resolve
  html_file <- file.path(docs_dir, "userguide_pdf_tmp.html")
  writeLines(enc2utf8(c(
    "<!DOCTYPE html><html><head><meta charset='utf-8'>",
    "<title>KBA Analysis App - User Guide</title>",
    "<style>", css, "</style></head><body>",
    html_body,
    "</body></html>"
  )), html_file, useBytes = TRUE)
  on.exit(unlink(html_file), add = TRUE)

  file_url <- paste0("file:///", gsub("\\\\", "/", normalizePath(html_file)))
  out_pdf  <- normalizePath(pdf_file, mustWork = FALSE)
  res <- system2(browser_exe, c(
    "--headless", "--disable-gpu", "--no-pdf-header-footer", "--print-to-pdf-no-header",
    "--no-first-run", "--disable-extensions",
    paste0('--print-to-pdf="', out_pdf, '"'),
    shQuote(file_url)
  ), stdout = FALSE, stderr = FALSE)

  if (res == 0 && file.exists(pdf_file) && difftime(Sys.time(), file.mtime(pdf_file), units = "secs") < 120) {
    message("Wrote ", pdf_file)
  } else {
    warning("PDF conversion failed (", basename(browser_exe), " exit code ", res, "): ", pdf_file, " was not updated.")
  }
  unlink(html_file)
}
